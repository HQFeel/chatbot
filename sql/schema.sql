-- USER는 MariaDB 키워드라서 항상 백틱으로 감싼다.
CREATE TABLE IF NOT EXISTS `USER` (
  USER_NO       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  LOGIN_ID      VARCHAR(30)     NOT NULL,
  PASSWORD_HASH VARCHAR(200)    NOT NULL,
  NICKNAME      VARCHAR(30)     NOT NULL,
  CREATED_AT    DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (USER_NO),
  UNIQUE KEY UK_USER_LOGIN_ID (LOGIN_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 채팅방 마스터
CREATE TABLE IF NOT EXISTS MESSAGE_MST (
  ROOM_NO        BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  ROOM_NAME      VARCHAR(50)     NOT NULL,
  CREATE_USER_NO BIGINT UNSIGNED NOT NULL,
  CREATED_AT     DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (ROOM_NO),
  CONSTRAINT FK_MESSAGE_MST_USER FOREIGN KEY (CREATE_USER_NO) REFERENCES `USER` (USER_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 채팅방 참여자
CREATE TABLE IF NOT EXISTS MESSAGE_MEMBER (
  ROOM_NO   BIGINT UNSIGNED NOT NULL,
  USER_NO   BIGINT UNSIGNED NOT NULL,
  JOINED_AT DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (ROOM_NO, USER_NO),
  KEY IX_MESSAGE_MEMBER_USER (USER_NO),
  CONSTRAINT FK_MESSAGE_MEMBER_ROOM FOREIGN KEY (ROOM_NO) REFERENCES MESSAGE_MST (ROOM_NO) ON DELETE CASCADE,
  CONSTRAINT FK_MESSAGE_MEMBER_USER FOREIGN KEY (USER_NO) REFERENCES `USER` (USER_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 메시지 상세
CREATE TABLE IF NOT EXISTS MESSAGE_DTL (
  MSG_NO     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  ROOM_NO    BIGINT UNSIGNED NOT NULL,
  USER_NO    BIGINT UNSIGNED NOT NULL,
  CONTENT    VARCHAR(1000)   NOT NULL,
  CREATED_AT DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (MSG_NO),
  KEY IX_MESSAGE_DTL_ROOM (ROOM_NO, MSG_NO),
  CONSTRAINT FK_MESSAGE_DTL_ROOM FOREIGN KEY (ROOM_NO) REFERENCES MESSAGE_MST (ROOM_NO) ON DELETE CASCADE,
  CONSTRAINT FK_MESSAGE_DTL_USER FOREIGN KEY (USER_NO) REFERENCES `USER` (USER_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
